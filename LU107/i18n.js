const setText = (selector, value) => {
  const element = document.querySelector(selector);
  if (element && element.textContent !== value) element.textContent = value;
};

const setHtml = (selector, value) => {
  const element = document.querySelector(selector);
  if (element && element.innerHTML !== value) element.innerHTML = value;
};

const setManyText = (selector, values) => {
  document.querySelectorAll(selector).forEach((element, index) => {
    if (values[index] !== undefined && element.textContent !== values[index]) element.textContent = values[index];
  });
};

const setControlText = (selector, value) => {
  const element = document.querySelector(selector);
  if (!element) return;
  const icon = element.querySelector('svg');
  if (!icon) {
    if (element.textContent !== value) element.textContent = value;
    return;
  }
  [...element.childNodes].forEach((node) => {
    if (node !== icon) node.remove();
  });
  element.insertBefore(document.createTextNode(`${value} `), icon);
};

const setManyControlText = (selector, values) => {
  document.querySelectorAll(selector).forEach((element, index) => {
    const value = values[index];
    if (value === undefined) return;
    const icon = element.querySelector('svg');
    if (!icon) {
      if (element.textContent !== value) element.textContent = value;
      return;
    }
    [...element.childNodes].forEach((node) => {
      if (node !== icon) node.remove();
    });
    element.insertBefore(document.createTextNode(`${value} `), icon);
  });
};

function ensureLanguageSwitcher() {
  const header = document.querySelector('.site-header');
  if (!header || header.querySelector('.language-switcher')) return;
  header.querySelector('nav')?.remove();
  const switcher = document.createElement('div');
  switcher.className = 'language-switcher';
  switcher.setAttribute('aria-label', 'Language');
  switcher.innerHTML = '<a href="#lv" data-language="lv" lang="lv">LV</a><a href="#en" data-language="en" lang="en">EN</a>';
  header.append(switcher);
}

function ensureGamePreview() {
  const frame = document.querySelector('.browser-frame');
  if (!frame || frame.querySelector('.game-launch-card')) return;
  frame.querySelector('.browser-bar')?.remove();
  frame.querySelector('iframe')?.remove();
  const card = document.createElement('a');
  card.className = 'game-launch-card';
  card.href = 'https://researchgames.eu/games/LU107/';
  card.target = '_blank';
  card.rel = 'noopener';
  const diagonalIcon = document.querySelector('.voice-option b svg')?.cloneNode(true);
  const roundImages = ['card-history.jpg', 'card-today.jpg', 'card-culture.jpg', 'card-image.png', 'card-final.jpg'];
  const rounds = roundImages.map((image, index) => `<li><div class="game-round-copy"><span class="game-round-number">${index + 1}</span><span class="game-round-name"></span></div><div class="game-round-photo" aria-hidden="true"><img src="https://researchgames.eu/games/LU107/assets/${image}" alt=""></div><span class="game-round-count"></span></li>`).join('');
  card.innerHTML = `<div class="game-launch-copy"><p class="game-launch-kicker"></p><h3 class="game-launch-title"></h3><p class="game-launch-text"></p><ul class="game-rounds">${rounds}</ul><span class="game-launch-button"><span class="game-launch-label"></span></span></div>`;
  if (diagonalIcon) card.querySelector('.game-launch-button')?.append(diagonalIcon);
  frame.append(card);
}

function ensureWishWallLayout() {
  const section = document.querySelector('.wish-section');
  const heading = section?.querySelector('.wish-heading');
  const form = heading?.querySelector('.wish-form');
  if (!section || !heading || !form) return;
  if (!section.hasAttribute('data-form-open')) section.setAttribute('data-form-open', 'false');
  let toggle = heading.querySelector('.wish-form-toggle');
  if (!toggle) {
    toggle = document.createElement('button');
    toggle.type = 'button';
    toggle.className = 'wish-form-toggle';
    toggle.setAttribute('aria-expanded', 'false');
    toggle.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-plus" aria-hidden="true"><path d="M5 12h14"></path><path d="M12 5v14"></path></svg>';
    heading.insertBefore(toggle, form);
  }
  toggle.setAttribute('aria-controls', 'lu107-wish-form');
  form.id = 'lu107-wish-form';
  const total = heading.querySelector('.wall-total');
  if (total && !total.querySelector('.wall-thanks')) {
    const thanks = document.createElement('span');
    thanks.className = 'wall-thanks';
    thanks.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-heart" aria-hidden="true"><path d="M19.5 12.572 12 20l-7.5-7.428A5 5 0 1 1 12 6.006a5 5 0 1 1 7.5 6.572"></path></svg><span class="wall-thanks-label"></span>';
    total.append(thanks);
  }
  let notice = heading.querySelector('.wish-submit-notice');
  if (!notice) {
    notice = document.createElement('p');
    notice.className = 'wish-submit-notice';
    notice.setAttribute('role', 'status');
    notice.hidden = true;
    heading.append(notice);
  }
  if (section.getAttribute('data-submit-notice') === 'true') notice.hidden = false;
}

function translatePage(language) {
  const lang = language === 'en' ? 'en' : 'lv';
  const t = translations[lang];
  document.documentElement.lang = lang;
  document.title = t.title;
  document.querySelector('meta[name="description"]')?.setAttribute('content', t.metaDescription);
  try {
    localStorage.setItem('lu107-language', lang);
  } catch {}
  ensureLanguageSwitcher();
  ensureGamePreview();
  ensureWishWallLayout();

  const gameUrl = `https://researchgames.eu/games/LU107/?lang=${lang}`;
  const gameCard = document.querySelector('.game-launch-card');
  if (gameCard) gameCard.href = gameUrl;

  const headerLogo = document.querySelector('.site-header .brand img');
  if (headerLogo) {
    headerLogo.src = t.headerLogo;
    headerLogo.alt = t.headerLogoAlt;
  }
  document.querySelector('.site-header .brand')?.setAttribute('aria-label', t.headerLogoAlt);

  setManyText('.site-header nav a', t.nav);
  setText('.hero-copy h1', t.heroTitle);
  setText('.hero-copy .lead', t.heroLead);
  setManyText('.hero-list li span', t.heroItems);
  setControlText('.hero-button', t.heroButton);
  setText('.choice-intro h2', t.choiceTitle);
  setManyText('.choice > .card-kicker', t.choiceKickers);
  setManyText('.choice-copy h3', t.choiceTitles);
  setManyText('.choice-copy > p', t.choiceTexts);
  setManyControlText('.choice-copy .button', t.choiceButtons);
  setText('.voice-heading .section-label', t.voiceLabel);
  setHtml('.voice-heading h2', t.voiceTitle);
  setText('.voice-heading > div:first-child > p:last-child', t.voiceIntro);
  setManyText('.voice-option h3', t.voiceTitles);
  setManyText('.voice-option p', t.voiceTexts);
  setManyControlText('.voice-option b', t.voiceButtons);
  setHtml('.game-section .section-heading h2', t.gameTitle);
  setText('.game-section .section-heading > p', t.gameIntro);
  setText('.browser-bar p', t.gameBar);
  setText('.game-launch-kicker', t.gamePreviewKicker);
  setText('.game-launch-title', t.gamePreviewTitle);
  setText('.game-launch-text', t.gamePreviewText);
  setManyText('.game-round-name', t.gameRounds);
  setManyText('.game-round-count', t.gameRoundCounts);
  setText('.game-launch-label', t.gameLaunch);
  const wishSection = document.querySelector('.wish-section');
  const wishHash = `#${t.wishAnchor}`;
  if (wishSection) wishSection.id = t.wishAnchor;
  document.querySelector('.site-header nav a:nth-child(3)')?.setAttribute('href', wishHash);
  document.querySelector('.choice-copy .button[href="#noveli"], .choice-copy .button[href="#apsveikumi"], .choice-copy .button[href="#greetings"]')?.setAttribute('href', wishHash);
  setHtml('.wish-heading > h2', t.wishTitle);
  setText('.wish-heading > p', t.wishIntro);
  setHtml('.wall-total span', t.wishCount);
  setText('.wall-thanks-label', t.wishThanks);
  setControlText('.wish-form-toggle', t.wishFormToggle);
  setText('.wish-form .section-label', t.formLabel);
  setText('.wish-form h3', t.formTitle);
  setHtml('.wish-form label:nth-of-type(1) > span', t.wishLabel);
  setHtml('.wish-form label:nth-of-type(2) > span', t.nameLabel);
  setText('.wish-form .consent span', t.consent);
  setControlText('.wish-form button', t.submit);
  setText('.wish-submit-notice', t.submitSuccess);
  setText('.wall-loading', t.loading);
  setText('#info-title', t.infoTitle);
  setHtml('#info .project-info-dialog p:nth-of-type(1)', t.infoLead);
  setHtml('#info .project-info-dialog p:nth-of-type(2)', t.infoProjects);
  setHtml('#info .project-info-contact', t.infoContact);
  setControlText('.project-info-link', t.infoLink);
  document.querySelector('.project-info-close')?.setAttribute('aria-label', t.infoClose);
  setHtml('.site-footer > p', t.copyright);

  const textarea = document.querySelector('.wish-form textarea');
  const nameInput = document.querySelector('.wish-form input:not([type="checkbox"])');
  if (textarea) textarea.placeholder = t.wishPlaceholder;
  if (nameInput) nameInput.placeholder = t.namePlaceholder;

  document.querySelectorAll('[data-language]').forEach((link) => {
    link.setAttribute('aria-current', link.dataset.language === lang ? 'true' : 'false');
  });

  const fullscreenLink = document.querySelector('.browser-bar a');
  if (fullscreenLink) {
    fullscreenLink.href = gameUrl;
    fullscreenLink.target = '_blank';
    fullscreenLink.rel = 'noopener';
  }

  if (location.hash.toLowerCase() === wishHash) {
    requestAnimationFrame(() => wishSection?.scrollIntoView({ block: 'start' }));
  }
}

function selectedLanguage() {
  const hash = location.hash.toLowerCase();
  if (hash === '#en' || hash === '#greetings') return 'en';
  if (hash === '#lv' || hash === '#apsveikumi') return 'lv';
  try {
    return localStorage.getItem('lu107-language') === 'en' ? 'en' : 'lv';
  } catch {
    return document.documentElement.lang === 'en' ? 'en' : 'lv';
  }
}

function applySelectedLanguage() {
  translatePage(selectedLanguage());
}

document.addEventListener('click', (event) => {
  const wishToggle = event.target.closest('.wish-form-toggle');
  if (wishToggle) {
    const section = wishToggle.closest('.wish-section');
    const isOpen = section?.getAttribute('data-form-open') === 'true';
    section?.setAttribute('data-form-open', String(!isOpen));
    wishToggle.setAttribute('aria-expanded', String(!isOpen));
    if (!isOpen) {
      section?.setAttribute('data-submit-notice', 'false');
      const notice = section?.querySelector('.wish-submit-notice');
      if (notice) notice.hidden = true;
    }
    if (!isOpen) section?.querySelector('.wish-form textarea')?.focus();
    return;
  }

  const languageLink = event.target.closest('[data-language]');
  if (languageLink) {
    event.preventDefault();
    history.replaceState(null, '', `#${languageLink.dataset.language}`);
    applySelectedLanguage();
    return;
  }

  const anchor = event.target.closest('a[href^="#"]:not([data-language])');
  if (!anchor) return;
  if (anchor.getAttribute('href') === '#info') return;
  const target = document.querySelector(anchor.getAttribute('href'));
  if (!target) return;
  event.preventDefault();
  target.scrollIntoView({ behavior: 'smooth', block: 'start' });
});

document.addEventListener('submit', (event) => {
  const form = event.target.closest?.('.wish-form');
  if (!form || !form.checkValidity()) return;
  const section = form.closest('.wish-section');
  section?.setAttribute('data-form-open', 'false');
  section?.setAttribute('data-submit-notice', 'true');
  section?.querySelector('.wish-form-toggle')?.setAttribute('aria-expanded', 'false');
  const showNotice = () => {
    ensureWishWallLayout();
    const lang = document.documentElement.lang === 'en' ? 'en' : 'lv';
    const notice = document.querySelector('.wish-submit-notice');
    if (notice) {
      notice.textContent = translations[lang].submitSuccess;
      notice.hidden = false;
    }
  };
  showNotice();
  setTimeout(showNotice, 150);
  setTimeout(showNotice, 700);
}, true);

if (!['#lv', '#en', '#info', '#apsveikumi', '#greetings'].includes(location.hash.toLowerCase())) {
  history.replaceState(null, '', '#lv');
}

window.addEventListener('hashchange', applySelectedLanguage);

const setText = (selector, value) => {
  const element = document.querySelector(selector);
  if (element && element.textContent !== value) element.textContent = value;
};

const setHtml = (selector, value) => {
  const element = document.querySelector(selector);
  if (element && element.innerHTML !== value) element.innerHTML = value;
};

const setManyText = (selector, values) => {
  document.querySelectorAll(selector).forEach((element, index) => {
    if (values[index] !== undefined && element.textContent !== values[index]) element.textContent = values[index];
  });
};

function ensureLanguageSwitcher() {
  const header = document.querySelector('.site-header');
  if (!header || header.querySelector('.language-switcher')) return;
  const switcher = document.createElement('div');
  switcher.className = 'language-switcher';
  switcher.setAttribute('aria-label', 'Language');
  switcher.innerHTML = '<a href="#lv" data-language="lv" lang="lv">LV</a><a href="#en" data-language="en" lang="en">EN</a>';
  header.append(switcher);
}

function translatePage(language) {
  const lang = language === 'en' ? 'en' : 'lv';
  const t = translations[lang];
  document.documentElement.lang = lang;
  document.title = t.title;
  try {
    localStorage.setItem('lu107-language', lang);
  } catch {}
  ensureLanguageSwitcher();

  setManyText('.site-header nav a', t.nav);
  setText('.hero-copy h1', t.heroTitle);
  setText('.hero-copy .lead', t.heroLead);
  setManyText('.hero-list li span', t.heroItems);
  setText('.hero-button', t.heroButton);
  setText('.choice-intro h2', t.choiceTitle);
  setManyText('.choice > .card-kicker', t.choiceKickers);
  setManyText('.choice-copy h3', t.choiceTitles);
  setManyText('.choice-copy > p', t.choiceTexts);
  setManyText('.choice-copy .button', t.choiceButtons);
  setText('.voice-heading .section-label', t.voiceLabel);
  setHtml('.voice-heading h2', t.voiceTitle);
  setText('.voice-heading > div:first-child > p:last-child', t.voiceIntro);
  setManyText('.voice-option h3', t.voiceTitles);
  setManyText('.voice-option p', t.voiceTexts);
  setManyText('.voice-option b', t.voiceButtons);
  setHtml('.game-section .section-heading h2', t.gameTitle);
  setText('.game-section .section-heading > p', t.gameIntro);
  setText('.browser-bar p', t.gameBar);
  setText('.browser-bar a', t.fullscreen);
  setHtml('.wish-heading > h2', t.wishTitle);
  setText('.wish-heading > p', t.wishIntro);
  setHtml('.wall-total span', t.wishCount);
  setText('.wish-form .section-label', t.formLabel);
  setText('.wish-form h3', t.formTitle);
  setHtml('.wish-form label:nth-of-type(1) > span', t.wishLabel);
  setHtml('.wish-form label:nth-of-type(2) > span', t.nameLabel);
  setText('.wish-form .consent span', t.consent);
  setText('.wish-form button', t.submit);
  setText('.wall-loading', t.loading);
  setText('#info-title', t.infoTitle);
  setHtml('#info .project-info-dialog p:nth-of-type(1)', t.infoLead);
  setHtml('#info .project-info-dialog p:nth-of-type(2)', t.infoProjects);
  setHtml('#info .project-info-contact', t.infoContact);
  setText('.project-info-link', t.infoLink);
  document.querySelector('.project-info-close')?.setAttribute('aria-label', t.infoClose);
  setHtml('.site-footer > p', t.copyright);

  const textarea = document.querySelector('.wish-form textarea');
  const nameInput = document.querySelector('.wish-form input:not([type="checkbox"])');
  if (textarea) textarea.placeholder = t.wishPlaceholder;
  if (nameInput) nameInput.placeholder = t.namePlaceholder;

  document.querySelectorAll('[data-language]').forEach((link) => {
    link.setAttribute('aria-current', link.dataset.language === lang ? 'true' : 'false');
  });

  const gameFrame = document.querySelector('.game-section iframe');
  if (gameFrame && gameFrame.src !== 'https://researchgames.eu/games/LU107/') {
    gameFrame.src = 'https://researchgames.eu/games/LU107/';
  }
  const fullscreenLink = document.querySelector('.browser-bar a');
  if (fullscreenLink) {
    fullscreenLink.href = 'https://researchgames.eu/games/LU107/';
    fullscreenLink.target = '_blank';
    fullscreenLink.rel = 'noopener';
  }
}

function selectedLanguage() {
  const hash = location.hash.toLowerCase();
  if (hash === '#en') return 'en';
  if (hash === '#lv') return 'lv';
  try {
    return localStorage.getItem('lu107-language') === 'en' ? 'en' : 'lv';
  } catch {
    return document.documentElement.lang === 'en' ? 'en' : 'lv';
  }
}

function applySelectedLanguage() {
  translatePage(selectedLanguage());
}

document.addEventListener('click', (event) => {
  const languageLink = event.target.closest('[data-language]');
  if (languageLink) {
    event.preventDefault();
    history.replaceState(null, '', `#${languageLink.dataset.language}`);
    applySelectedLanguage();
    return;
  }

  const anchor = event.target.closest('a[href^="#"]:not([data-language])');
  if (!anchor) return;
  if (anchor.getAttribute('href') === '#info') return;
  const target = document.querySelector(anchor.getAttribute('href'));
  if (!target) return;
  event.preventDefault();
  target.scrollIntoView({ behavior: 'smooth', block: 'start' });
});

if (!['#lv', '#en', '#info'].includes(location.hash.toLowerCase())) {
  history.replaceState(null, '', '#lv');
}

window.addEventListener('hashchange', applySelectedLanguage);
window.addEventListener('load', applySelectedLanguage, { once: true });
setTimeout(applySelectedLanguage, 1100);
applySelectedLanguage();
